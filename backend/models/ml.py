"""
ForecastModel, ForecastResult, ForecastPeriod, ForecastSnapshot SQLAlchemy async models.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, Integer, Numeric, String
from sqlalchemy.orm import Mapped, mapped_column

from models.base import Base, GUID, JsonType


class ForecastModel(Base):
    """A trained ML forecast model scoped to an AccountSet."""

    __tablename__ = "forecast_models"

    id: Mapped[uuid.UUID] = mapped_column(
        GUID(), primary_key=True, default=uuid.uuid4
    )
    account_set_id: Mapped[uuid.UUID] = mapped_column(
        GUID(), ForeignKey("account_sets.id"), nullable=False, index=True
    )
    model_type: Mapped[str] = mapped_column(String(64), nullable=False)
    artifact_path: Mapped[str] = mapped_column(String(512), nullable=False)
    trained_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )
    mape: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    rmse: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)

    def __repr__(self) -> str:
        return f"<ForecastModel id={self.id} type={self.model_type}>"


class ForecastResult(Base):
    """A forecast result generated by a ForecastModel."""

    __tablename__ = "forecast_results"

    id: Mapped[uuid.UUID] = mapped_column(
        GUID(), primary_key=True, default=uuid.uuid4
    )
    account_set_id: Mapped[uuid.UUID] = mapped_column(
        GUID(), ForeignKey("account_sets.id"), nullable=False, index=True
    )
    model_id: Mapped[uuid.UUID] = mapped_column(
        GUID(), ForeignKey("forecast_models.id"), nullable=False, index=True
    )
    generated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )
    horizon_months: Mapped[int] = mapped_column(Integer, nullable=False)

    def __repr__(self) -> str:
        return f"<ForecastResult id={self.id} horizon={self.horizon_months}>"


class ForecastPeriod(Base):
    """A single period's predicted cash flow within a ForecastResult."""

    __tablename__ = "forecast_periods"

    id: Mapped[uuid.UUID] = mapped_column(
        GUID(), primary_key=True, default=uuid.uuid4
    )
    result_id: Mapped[uuid.UUID] = mapped_column(
        GUID(), ForeignKey("forecast_results.id"), nullable=False, index=True
    )
    period_code: Mapped[str] = mapped_column(String(8), nullable=False)
    predicted_inflow: Mapped[float] = mapped_column(Numeric(18, 4), nullable=False, default=0)
    predicted_outflow: Mapped[float] = mapped_column(Numeric(18, 4), nullable=False, default=0)
    predicted_net_cash_flow: Mapped[float] = mapped_column(Numeric(18, 4), nullable=False, default=0)
    confidence_lower: Mapped[float] = mapped_column(Numeric(18, 4), nullable=False, default=0)
    confidence_upper: Mapped[float] = mapped_column(Numeric(18, 4), nullable=False, default=0)

    def __repr__(self) -> str:
        return f"<ForecastPeriod id={self.id} period={self.period_code}>"


class ForecastSnapshot(Base):
    """A snapshot of a forecast result for historical comparison."""

    __tablename__ = "forecast_snapshots"

    id: Mapped[uuid.UUID] = mapped_column(
        GUID(), primary_key=True, default=uuid.uuid4
    )
    account_set_id: Mapped[uuid.UUID] = mapped_column(
        GUID(), ForeignKey("account_sets.id"), nullable=False, index=True
    )
    result_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        GUID(), ForeignKey("forecast_results.id"), nullable=True, index=True
    )
    snapshot_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )
    snapshot_period: Mapped[Optional[str]] = mapped_column(String(8), nullable=True, index=True)
    target_period: Mapped[Optional[str]] = mapped_column(String(8), nullable=True, index=True)
    predicted_net_cash_flow: Mapped[Optional[float]] = mapped_column(Numeric(18, 4), nullable=True)
    confidence_lower: Mapped[Optional[float]] = mapped_column(Numeric(18, 4), nullable=True)
    confidence_upper: Mapped[Optional[float]] = mapped_column(Numeric(18, 4), nullable=True)
    actual_net_cash_flow: Mapped[Optional[float]] = mapped_column(Numeric(18, 4), nullable=True)
    notes: Mapped[Optional[str]] = mapped_column(String(512), nullable=True)

    def __repr__(self) -> str:
        return f"<ForecastSnapshot id={self.id}>"
